function study = run_full_trajectory_factor_graph_parity_5s(seed,windowSeconds)
%RUN_FULL_TRAJECTORY_FACTOR_GRAPH_PARITY_5S Fixed-Q raw/FG comparison.
% Both cases use the same window truth, bearings, prior, and FOGM covariance.

    if nargin < 1 || isempty(seed), seed = 101; end
    if nargin < 2 || isempty(windowSeconds), windowSeconds = 5.0; end
    validateattributes(windowSeconds,{'numeric'},{'scalar','positive','finite'});
    common = {seed,windowSeconds,false,4,0.1,3};
    raw = run_toy_block_structured_global_head_dnn_ekf(common{:}, ...
        "centralized_common_dnn_periodic_fixed_q",3,4,"all_to_all",[],windowSeconds);
    fg = run_toy_block_structured_global_head_dnn_ekf(common{:}, ...
        "centralized_common_dnn_full_trajectory_fg_5s",3,4,"all_to_all",[],windowSeconds);

    assert(isequal(raw.truth,fg.truth),"Parity cases have different truth trajectories.");
    assert(~raw.cfg.collaborative.enableCovarianceMatching, ...
        "Raw replay covariance matching must be disabled for this comparison.");
    assert(~raw.cfg.collaborative.enableParameterClipping && ...
        ~fg.cfg.collaborative.enableParameterClipping, ...
        "Parity cases must not use parameter clipping.");
    r = raw.sharedBlock; g = fg.sharedBlock;
    etaRaw = r.etaHat(:,end,1); etaFG = g.etaHat(:,end,1);
    study = struct("raw",r,"factorGraph",g,"seed",seed,"windowSeconds",windowSeconds, ...
        "endpointStateDifference",norm(etaRaw-etaFG), ...
        "rawFinalPositionRMSE",r.finalPositionRMSE, ...
        "factorGraphFinalPositionRMSE",g.finalPositionRMSE, ...
        "factorGraphAcceptedCosts",{g.acceptedCosts});
    fprintf("Fixed-Q %.3g-s parity: raw final RMSE=%.6g m, FG final RMSE=%.6g m, endpoint state difference=%.6g.\n", ...
        windowSeconds,study.rawFinalPositionRMSE,study.factorGraphFinalPositionRMSE,study.endpointStateDifference);
end
